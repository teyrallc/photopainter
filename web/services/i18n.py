"""
Interface strings for the Vignette web console.

English (en) and Traditional Chinese (zh). Every key must exist in both
dictionaries — the whole table is handed to the browser as JSON, so a key
missing from one language shows up as a raw identifier in the UI.
"""


class Translations(dict):
    """A string table whose attribute access always means a key lookup.

    Templates read strings as ``{{ t.clear }}``, and Jinja resolves that with
    ``getattr`` before falling back to ``__getitem__``. On a plain dict the
    ``clear`` key therefore resolved to ``dict.clear`` and the button rendered
    as ``<built-in method clear of dict object at 0x…>``; ``update``, ``pop``,
    ``copy``, ``items``, ``keys`` and ``values`` are all the same trap waiting
    for the next translator.

    Staying a real ``dict`` keeps ``| tojson`` and ``json.dumps`` working, so
    only the lookup order changes: keys win, dunders always go to the dict, and
    anything that is not a key still resolves to the normal dict attribute.
    """

    def __getattribute__(self, name):
        if not name.startswith("__"):
            try:
                return dict.__getitem__(self, name)
            except KeyError:
                pass
        return dict.__getattribute__(self, name)


