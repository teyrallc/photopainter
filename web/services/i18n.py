_BASE = set(TRANSLATIONS["en"])
for _lang, _strings in TRANSLATIONS.items():
    _missing = _BASE - set(_strings)
    if _missing:
        raise RuntimeError(
            "i18n: %r is missing %s" % (_lang, ", ".join(sorted(_missing)))
        )


def get_translations(lang="en"):
    """Return the string table for a language, falling back to English."""
    return TRANSLATIONS.get(lang, TRANSLATIONS["en"])
